        "def plot_derivative_and_integral(func, x_range=(-5, 5), integral_range=(-2, 3), num_points=500):\n",
        "    \"\"\"\n",
        "    주어진 함수의 원래 그래프, 미분 그래프, 지정 구간의 적분 영역을 그립니다.\n",
        "\n",
        "    :param func: 호출 가능한 함수 (일반 파이썬 함수 또는 ctypes C 함수 포인터)\n",
        "    :param x_range: 전체 그래프를 그릴 x 범위 (start, end)\n",
        "    :param integral_range: 적분 영역을 색칠하고 넓이를 계산할 x 범위 (a, b)\n",
        "    :param num_points: 그래프 해상도 (점의 개수)\n",
        "    \"\"\"\n",
        "    # 1. x 좌표 생성\n",
        "    x = np.linspace(x_range[0], x_range[1], num_points)\n",
        "\n",
        "    # 2. 원래 함수값 y 계산\n",
        "    # C 함수 포인터(ctypes)는 numpy 배열을 직접 받지 못하므로 리스트 컴프리헨션으로 하나씩 호출합니다.\n",
        "    y = np.array([func(float(val)) for val in x], dtype=float)\n",
        "\n",
        "    # 3. 수치 미분 계산 (중앙 차분법 기반 np.gradient 사용)\n",
        "    dy_dx = np.gradient(y, x)\n",
        "\n",
        "    # 4. 지정된 구간 [a, b]의 수치 적분 계산 (사다리꼴 공식 np.trapezoid / np.trapz)\n",
        "    a, b = integral_range\n",
        "    x_int = np.linspace(a, b, num_points)\n",
        "    y_int = np.array([func(float(val)) for val in x_int], dtype=float)\n",
        "\n",
        "    # NumPy 2.0 이상은 trapezoid, 미만은 trapz 사용\n",
        "    integral_value = np.trapezoid(y_int, x_int) if hasattr(np, 'trapezoid') else np.trapz(y_int, x_int)\n",
        "\n",
        "    # 5. 그래프 그리기\n",
        "    fig, ax = plt.subplots(figsize=(10, 6))\n",
        "\n",
        "    # 원래 함수 f(x)\n",
        "    ax.plot(x, y, label='원래 함수 f(x)', color='#1f77b4', linewidth=2.5)\n",
        "\n",
        "    # 미분 함수 f'(x)\n",
        "    ax.plot(x, dy_dx, label=\"미분 함수 f'(x)\", color='#ff7f0e', linestyle='--', linewidth=2)\n",
        "\n",
        "    # 적분 영역 색칠 (a <= x <= b)\n",
        "    ax.fill_between(\n",
        "        x_int, y_int, 0,\n",
        "        color='#2ca02c', alpha=0.3,\n",
        "        label=f'적분 영역 [{a}, {b}] ≈ {integral_value:.4f}'\n",
        "    )\n",
        "\n",
        "    # 기준선 (x축, y축) 및 스타일 설정\n",
        "    ax.axhline(0, color='black', linewidth=0.8)\n",
        "    ax.axvline(0, color='black', linewidth=0.8)\n",
        "    ax.grid(True, linestyle=':', alpha=0.6)\n",
        "\n",
        "    ax.set_title('함수의 미분 그래프 및 정적분 영역 시각화', fontsize=14, fontweight='bold')\n",
        "    ax.set_xlabel('x', fontsize=12)\n",
        "    ax.set_ylabel('y', fontsize=12)\n",
        "    ax.legend(fontsize=11, loc='best')\n",
        "\n",
        "    plt.tight_layout()\n",
        "    plt.show()\n",
        "\n",
