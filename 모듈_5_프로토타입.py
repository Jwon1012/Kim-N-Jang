        "import platform\n",
        "import matplotlib.pyplot as plt\n",
        "from matplotlib.widgets import Button, Slider\n",
        "import numpy as np\n",
        "\n",
        "# OS별 한글 폰트 설정\n",
        "if platform.system() == 'Windows':\n",
        "    plt.rc('font', family='Malgun Gothic')\n",
        "elif platform.system() == 'Darwin':\n",
        "    plt.rc('font', family='AppleGothic')\n",
        "plt.rcParams['axes.unicode_minus'] = False\n",
        "\n",
        "\n",
        "def interactive_calculus_plot(\n",
        "    func, x_range=(-5.0, 5.0), init_a=-1.5, init_b=2.0, num_points=600\n",
        "):\n",
        "    \"\"\"\n",
        "    슬라이더로 적분 구간 [a, b]를 실시간 조절하며 미분 그래프와 적분 영역을 확인합니다.\n",
        "    \"\"\"\n",
        "    x_min, x_max = x_range\n",
        "    x = np.linspace(x_min, x_max, num_points)\n",
        "\n",
        "    # C 함수 포인터(ctypes)와 일반 파이썬 함수 모두 호환되도록 계산\n",
        "    y = np.array([func(float(val)) for val in x], dtype=float)\n",
        "    dy_dx = np.gradient(y, x)\n",
        "\n",
        "    # 그래프 레이아웃 생성 (하단에 슬라이더 공간 확보를 위해 bottom 여백 조정)\n",
        "    fig, ax = plt.subplots(figsize=(10, 7))\n",
        "    plt.subplots_adjust(bottom=0.25)\n",
        "\n",
        "    # 1. 고정 그래프 그리기 (원래 함수 및 미분 함수)\n",
        "    ax.plot(x, y, label='원래 함수 f(x)', color='#1f77b4', linewidth=2.5)\n",
        "    ax.plot(\n",
        "        x,\n",
        "        dy_dx,\n",
        "        label=\"미분 함수 f'(x)\",\n",
        "        color='#ff7f0e',\n",
        "        linestyle='--',\n",
        "        linewidth=1.8,\n",
        "    )\n",
        "\n",
        "    ax.axhline(0, color='black', linewidth=0.8)\n",
        "    ax.axvline(0, color='black', linewidth=0.8)\n",
        "    ax.grid(True, linestyle=':', alpha=0.6)\n",
        "    ax.set_xlim(x_min, x_max)\n",
        "    ax.set_title(\n",
        "        '실시간 정적분 영역 및 미분 그래프', fontsize=14, fontweight='bold'\n",
        "    )\n",
        "    ax.set_xlabel('x', fontsize=11)\n",
        "    ax.set_ylabel('y', fontsize=11)\n",
        "\n",
        "    # 2. 적분 계산 및 영역 채우기 헬퍼 함수\n",
        "    def calc_integral(a, b):\n",
        "        x_int = np.linspace(a, b, 300)\n",
        "        y_int = np.array([func(float(val)) for val in x_int], dtype=float)\n",
        "        val = (\n",
        "            np.trapezoid(y_int, x_int)\n",
        "            if hasattr(np, 'trapezoid')\n",
        "            else np.trapz(y_int, x_int)\n",
        "        )\n",
        "        return x_int, y_int, val\n",
        "\n",
        "    # 초기 적분 영역 렌더링\n",
        "    x_int, y_int, init_val = calc_integral(init_a, init_b)\n",
        "    fill_poly = ax.fill_between(x_int, y_int, 0, color='#2ca02c', alpha=0.35)\n",
        "\n",
        "    # 시작점(a), 끝점(b) 수직 점선 표시\n",
        "    line_a = ax.axvline(init_a, color='#2ca02c', linestyle='-.', linewidth=1.2)\n",
        "    line_b = ax.axvline(init_b, color='#d62728', linestyle='-.', linewidth=1.2)\n",
        "\n",
        "    # 적분 결과 텍스트 박스 (좌측 상단 고정)\n",
        "    info_text = ax.text(\n",
        "        0.03,\n",
        "        0.95,\n",
        "        f'적분 구간: [{init_a:.2f}, {init_b:.2f}]\\n정적분 값: {init_val:.4f}',\n",
        "        transform=ax.transAxes,\n",
        "        fontsize=11,\n",
        "        verticalalignment='top',\n",
        "        bbox=dict(\n",
        "            boxstyle='round,pad=0.5',\n",
        "            facecolor='#f0f9f0',\n",
        "            edgecolor='#2ca02c',\n",
        "            alpha=0.9,\n",
        "        ),\n",
        "    )\n",
        "    ax.legend(loc='upper right', fontsize=10)\n",
        "\n",
        "    # 3. 슬라이더 UI 배치 [left, bottom, width, height]\n",
        "    ax_a = plt.axes([0.18, 0.12, 0.65, 0.03])\n",
        "    ax_b = plt.axes([0.18, 0.07, 0.65, 0.03])\n",
        "\n",
        "    slider_a = Slider(\n",
        "        ax=ax_a,\n",
        "        label='시작점 (a)',\n",
        "        valmin=x_min,\n",
        "        valmax=x_max,\n",
        "        valinit=init_a,\n",
        "        color='#2ca02c',\n",
        "    )\n",
        "    slider_b = Slider(\n",
        "        ax=ax_b,\n",
        "        label='끝점 (b)',\n",
        "        valmin=x_min,\n",
        "        valmax=x_max,\n",
        "        valinit=init_b,\n",
        "        color='#d62728',\n",
        "    )\n",
        "\n",
        "    # 4. 슬라이더 조작 시 실행되는 업데이트 콜백\n",
        "    def update(val):\n",
        "        nonlocal fill_poly\n",
        "        a = slider_a.val\n",
        "        b = slider_b.val\n",
        "\n",
        "        # 기존 색칠 영역 제거 후 새 구간으로 다시 그리기\n",
        "        fill_poly.remove()\n",
        "        new_x, new_y, integral_val = calc_integral(a, b)\n",
        "\n",
        "        # a > b 일 경우(역방향 적분) 붉은색 계열로 시각적 구분\n",
        "        fill_color = '#2ca02c' if a <= b else '#d62728'\n",
        "        fill_poly = ax.fill_between(\n",
        "            new_x, new_y, 0, color=fill_color, alpha=0.35\n",
        "        )\n",
        "\n",
        "        # 경계선 및 텍스트 업데이트\n",
        "        line_a.set_xdata([a, a])\n",
        "        line_b.set_xdata([b, b])\n",
        "        info_text.set_text(\n",
        "            f'적분 구간: [{a:.2f}, {b:.2f}]\\n정적분 값: {integral_val:.4f}'\n",
        "        )\n",
        "\n",
        "        fig.canvas.draw_idle()\n",
        "\n",
        "    slider_a.on_changed(update)\n",
        "    slider_b.on_changed(update)\n",
        "\n",
        "    # 5. 초기화(Reset) 버튼 추가\n",
        "    ax_reset = plt.axes([0.86, 0.07, 0.08, 0.08])\n",
        "    btn_reset = Button(ax_reset, '초기화', hovercolor='0.9')\n",
        "\n",
        "    def reset(event):\n",
        "        slider_a.reset()\n",
        "        slider_b.reset()\n",
        "\n",
        "    btn_reset.on_clicked(reset)\n",
        "\n",
        "    plt.show()\n",
        "\n",
        "\n",
        "# ==========================================\n",
